// Map age group to its adventure activities
export const ADVENTURE_ACTIVITIES: Record<string, Activity[]> = {
  bercario: ADVENTURE_ACTIVITIES_BERCARIO,
  maternal: ADVENTURE_ACTIVITIES_MATERNAL,
  'pre-escola-1': ADVENTURE_ACTIVITIES_PRE1,
  'pre-escola-2': ADVENTURE_ACTIVITIES_PRE2,
};

/**
 * Get the adventure activity for a specific level and age group
 */
const DIFFICULTY_RANK: Record<string, number> = { facil: 0, medio: 1, dificil: 2 };
const levelOrderCache: Record<string, Activity[]> = {};

/**
 * As 100 atividades da faixa na ordem das fases: dentro de cada mundo (10 fases),
 * do mais fácil para o mais difícil, sem trocar atividades de mundo (o tema continua o mesmo).
 */
function levelOrder(ageGroup: string): Activity[] {
  if (levelOrderCache[ageGroup]) return levelOrderCache[ageGroup];
  const base = (ADVENTURE_ACTIVITIES[ageGroup] ?? []).slice(0, 100);
  const ordered: Activity[] = [];
  for (let start = 0; start < base.length; start += 10) {
    const world = base.slice(start, start + 10);
    // sort estável: atividades da mesma dificuldade mantêm a ordem original
    ordered.push(...world.slice().sort((x, y) => (DIFFICULTY_RANK[x.difficulty] ?? 0) - (DIFFICULTY_RANK[y.difficulty] ?? 0)));
  }
  levelOrderCache[ageGroup] = ordered;
  return ordered;
}

export function getAdventureActivity(levelNumber: number, ageGroup: string): Activity | null {
  if (levelNumber < 1 || levelNumber > 100) return null;
  return levelOrder(ageGroup)[levelNumber - 1] || null;
}

